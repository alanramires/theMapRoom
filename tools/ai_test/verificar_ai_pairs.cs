using System.Reflection;
var method = typeof(AIController).GetMethod("BuildAIReviewVisualPairs", BindingFlags.Static | BindingFlags.Public);
if (method == null) return "WAIT: saia e volte ao Play para importar BuildAIReviewVisualPairs; sem recompile em Play.";
var a = new UnityEngine.Vector3Int(2, 3, 0);
var b = new UnityEngine.Vector3Int(4, 3, 0);
var c = new UnityEngine.Vector3Int(6, 4, 0);
var d = new UnityEngine.Vector3Int(5, 4, 0);
System.Collections.IList Pairs(PlayerAction action) => (System.Collections.IList)method.Invoke(null, new object[] { action });
UnityEngine.Vector3Int Cell(object pair, string field) => (UnityEngine.Vector3Int)pair.GetType().GetField(field).GetValue(pair);
PlayerAction Action(SensorActionType kind) => new PlayerAction { ActionType = PlayerActionType.UnitAction, SensorAction = kind, HasMoveFrom = true, MoveFrom = a, HasMoveTo = true, MoveTo = b };
var attack = Action(SensorActionType.Attack);
attack.HasTargetHex = true; attack.TargetHex = c;
var pairs = Pairs(attack);
if (pairs.Count != 2 || Cell(pairs[0], "From") != a || Cell(pairs[0], "To") != b || Cell(pairs[1], "From") != b || Cell(pairs[1], "To") != c) throw new System.Exception("Movimento+ataque: pares incorretos.");
var capture = Pairs(Action(SensorActionType.Capture));
if (capture.Count != 2 || Cell(capture[1], "From") != b || Cell(capture[1], "To") != b) throw new System.Exception("Captura no destino sem marcador.");
var disembark = Action(SensorActionType.Disembark);
disembark.SubSteps.Add(new PlayerActionSubStep { HasTargetHex = true, TargetHex = c, TargetInstanceId = "passageiro-1" });
disembark.SubSteps.Add(new PlayerActionSubStep { HasTargetHex = true, TargetHex = d, TargetInstanceId = "passageiro-2" });
var cargo = Pairs(disembark);
if (cargo.Count != 3 || Cell(cargo[1], "To") != c || Cell(cargo[2], "To") != d) throw new System.Exception("Desembarque nao mostrou todos os destinos.");
var embark = Action(SensorActionType.Embark);
embark.HasTargetHex = true; embark.TargetHex = c;
if (Pairs(embark).Count != 2) throw new System.Exception("Embarque sem par para transporte.");
var supply = Action(SensorActionType.Supply);
supply.HasTargetHex = true; supply.TargetHex = c;
supply.SubSteps.Add(new PlayerActionSubStep { HasTargetHex = true, TargetHex = c });
supply.SubSteps.Add(new PlayerActionSubStep { HasTargetHex = true, TargetHex = d });
if (Pairs(supply).Count != 3) throw new System.Exception("Alvos de suprimento duplicados ou ausentes.");
if (Pairs(new PlayerAction { ActionType = PlayerActionType.EndTurn }).Count != 0) throw new System.Exception("Passar turno nao deve gerar pares.");
return "PASS: movimento+ataque, captura no destino, dois desembarques, embarque, suprimento multialvo sem duplicacao e passar turno. Nenhuma jogada executada.";
